#ifndef __SCHEDULER_H
#define __SCHEDULER_H

#include "main.h"

/*===========================================================================
 * 任务优先级
 *   数值越小优先级越高。抢占只在"更高优先级任务就绪"时发生。
 *
 *  TASK_PRIO_NORMAL : 用户任务默认优先级，多个任务可共用同一优先级，
 *                     同优先级内按 FIFO 轮转调度，保证公平。
 *  TASK_PRIO_IDLE   : 空闲任务固定为最低优先级。Idle 不再被特殊对待，
 *                     它只是"优先级最低、且永不阻塞"的普通任务。
 *=========================================================================*/
#define TASK_PRIO_IDLE     255
#define TASK_PRIO_NORMAL   1

/*===========================================================================
 * 内核预留任务的栈大小（单位：字，1 字 = 4 字节）
 *
 * 空闲任务 IDLE 是调度器自带的兜底任务，故其栈宏定义于此。
 * 用户任务的栈大小宏由各应用层模块自行定义并传入 create，
 * 不在本头文件中声明 —— 调度器不依赖任何具体模块。
 *
 * 上下文帧开销（任何任务被抢占瞬间的固定消耗）：
 *   硬件帧 xPSR/PC/LR/R12/R0-R3     8 字
 *   FPU 帧 S0-S15 + FPSCR + 对齐   18 字（任务用过 FPU 后才有）
 *   软件帧 R4-R11 + EXC_RETURN      9 字
 *   PendSV 追加 S16-S31            16 字（FPCA=1 时）
 *   ─────────────────────────────────────
 *   最坏合计                       51 字
 *
 * 因此 MIN_STACK_WORDS（64 字 = 256 B）是最低安全线，
 * 它保证即使任务自身代码几乎不用栈，也能容纳一次完整上下文切换。
 *=========================================================================*/
#define IDLE_STACK_SIZE    64     /*  256 B：仅 __WFI()，不使用 FPU，帧开销最小 */

/*===========================================================================
 * 任务栈最小容量（单位：字）
 *
 * 必须能容纳最坏情况下的上下文帧，否则任务一被抢占就会写穿栈底：
 *
 *   硬件帧 xPSR/PC/LR/R12/R0-R3     8 字
 *   FPU 帧 S0-S15 + FPSCR + 对齐   18 字（任务用过 FPU 后才有）
 *   软件帧 R4-R11 + EXC_RETURN      9 字
 *   PendSV 追加 S16-S31            16 字（FPCA=1 时）
 *   ─────────────────────────────────────
 *   最坏合计                       51 字
 *
 * 取 64 字（256 B）留出余量。
 * !! 本值必须 <= IDLE_STACK_SIZE !!
 *    否则空闲任务自身都无法通过参数校验，系统将无法启动。
 *=========================================================================*/
#define MIN_STACK_WORDS    64

/*===========================================================================
 * 栈高水位检测
 *
 * 原理：任务栈在初始化时被统一填充为 STACK_FILL_PATTERN。
 *       任务运行期间栈向下（低地址）增长，用到的地方魔数被覆盖；
 *       而 SP 退回后不会变回魔数，因此栈底一侧残留的魔数长度，
 *       就精确记录了"该任务历史上从未触碰过的栈空间"。
 *
 *       剩余比例建议判据：
 *         > 50% 安全 | 30%~50% 可接受 | < 30% 偏紧 | = 0 已溢出
 *
 * 局限：只能反映"实际执行过的路径"。必须让所有分支（含 1Hz 打印、
 *       静止/旋转两条路径）都跑到，测出的峰值才有意义。
 *=========================================================================*/
#define STACK_FILL_PATTERN  0xA5A5A5A5UL

typedef enum {
    TASK_READY     = 0,
    TASK_RUNNING   = 1,
    TASK_BLOCKED   = 2,
    TASK_SUSPENDED = 3,
} TaskState_t;

/*---------------------------------------------------------------------------
 * 任务控制块 (TCB)
 *
 * !! stack_ptr 必须是第一个成员 !!
 * port_asm.s 中的 PendSV_Handler 通过偏移 0 直接访问此字段。
 * 其余成员可自由调整，不影响汇编层。
 *
 * next —— 单向链表指针，用于把 TCB 串入就绪链或阻塞链。
 *         任一时刻一个 TCB 只挂在其中一条链上，三者互斥：
 *
 *           就绪链 (ready_head)   : 只放 READY 状态的任务
 *           阻塞链 (blocked_head) : 只放 BLOCKED 状态的任务
 *           正在运行的任务        : 已从就绪链摘出，仅由 current_tcb 指向
 *
 *         因此"遍历系统中所有任务"必须同时覆盖两链与 current_tcb，
 *         只遍历链表会漏掉当前任务。
 *
 *         就绪链按优先级升序排列、同优先级内 FIFO，故链头恒为
 *         "最高优先级中最早就绪者"，选择任务退化为 O(1)。
 *--------------------------------------------------------------------------*/
typedef struct TCB {
    uint32_t    *stack_ptr;      /* 当前栈指针（必须第一个成员）        */
    uint32_t    *stack_base;     /* 栈底地址，供栈高水位检测使用        */
    uint32_t     stack_words;    /* 栈容量（字）                        */
    uint8_t      prio;           /* 优先级，数值越小越高                */
    TaskState_t  state;
    uint32_t     delay_ticks;
    const char  *name;
    struct TCB  *next;           /* 就绪链 / 阻塞链，单向               */
} TCB_t;

/*---------------------------------------------------------------------------
 * 对外 API
 *--------------------------------------------------------------------------*/
void     scheduler_init(void);          /* 初始化任务与调度器（尚未启动） */
void     scheduler_start(void);         /* 选出首个任务并启动，不返回     */
void     scheduler_delay(uint32_t ms);  /* 阻塞当前任务 ms 毫秒           */
void     scheduler_tick(void);          /* 由 port_timer.c 的 TIM6 中断每 1ms 调用 */

/*---------------------------------------------------------------------------
 * 动态创建任务
 *
 * TCB 与任务栈均从 port_mem 的内存池中分配（bump allocator，不支持释放），
 * 因此创建出的任务会一直存在 —— 适用于"启动时或模块初始化时创建、
 * 之后不再删除"的场景。
 *
 *   func        : 任务入口函数，必须是 while(1) 形式，不得返回
 *   name        : 任务名（调试用）。必须指向字符串字面量或长期有效的内存，
 *                 不可传局部数组；可为 NULL
 *   prio        : 优先级，数值越小越高；可用 TASK_PRIO_NORMAL / TASK_PRIO_IDLE
 *   stack_words : 栈容量（单位：字），必须 >= MIN_STACK_WORDS
 *
 * 返回：成功返回任务句柄（供 scheduler_stack_free() 等使用）；
 *       失败返回 NULL（参数非法或内存池空间不足）。
 *
 * 注意：本函数可在调度器启动前后调用。
 *       若在启动后创建了一个优先级更高的任务，会立即触发抢占。
 *--------------------------------------------------------------------------*/
TCB_t   *scheduler_task_create(void (*func)(void), const char *name,
                               uint8_t prio, uint32_t stack_words);

/* 查询指定任务"从未使用过"的栈空间（单位：字）。
   handle 为创建任务时返回的句柄；0 表示该任务已把栈用到栈底（溢出）。 */
uint32_t scheduler_stack_free(TCB_t *handle);

/*---------------------------------------------------------------------------
 * 供 port_asm.s 访问
 *--------------------------------------------------------------------------*/
void   scheduler_switch_context(void);
extern TCB_t *current_tcb;

#endif /* __SCHEDULER_H */
