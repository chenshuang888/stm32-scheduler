#ifndef __SCHEDULER_SEM_H
#define __SCHEDULER_SEM_H

#include "main.h"

/*===========================================================================
 * scheduler_sem — 计数信号量
 *
 * 定位：与 scheduler_queue 同级的 IPC 组件。内核（scheduler.c）不依赖它，
 *       它建立在内核的 scheduler_wait_prepare() / scheduler_wake_one() 之上。
 *
 * ---------------------------------------------------------------------------
 * 二值与计数
 * ---------------------------------------------------------------------------
 * 本实现是**计数信号量**，二值是 max == 1 时的特例：
 *
 *   max = 1 → 二值信号量：只记"有事发生 / 没有"，多次 give 会合并
 *   max > 1 → 计数信号量：能记住"发生了几次"，超限后饱和丢弃
 *
 * 典型用法：
 *   二值  ：中断通知任务"某事件发生了"（只关心有没有，不关心几次）
 *   计数 ：中断通知任务"来了 N 个数据块"，任务逐块处理（不能合并）
 *
 * 本项目的用途是串口 DMA 接收：IDLE 中断里 give，接收任务阻塞 take。
 * 用计数（max 设几）而非二值，是为了在任务处理慢时不把多帧合并成一次。
 *
 * ---------------------------------------------------------------------------
 * give 的"过继"语义（重要）
 * ---------------------------------------------------------------------------
 * give 时若有任务正阻塞在本信号量上，令牌**直接交给它**，count 不增加；
 * 没有任务等待时才 count++。
 *
 * 这样被唤醒的任务无需再减 count —— 它拿到的就是这次 give 的令牌。
 * 若改成"count++ 再唤醒"，任务醒来后还要再减一次，中间若被别的任务
 * 抢先减掉，就会出现"唤醒了却拿不到令牌"的诡异情况。
 *
 * ---------------------------------------------------------------------------
 * 中断中调用
 * ---------------------------------------------------------------------------
 * give 不阻塞，只做"改 count + 可能唤醒一个任务"，可在 ISR 中直接调用。
 * 若被唤醒的任务优先级更高，会置位 PendSV，等 ISR 退出后立即抢占 ——
 * 这正是中断驱动模型的意义：事件到达后任务被立刻调度。
 *
 * take 会阻塞当前任务，**只能在任务上下文调用**。
 * 调度器尚未启动时调用 take 会退化为"看一眼就返回"的非阻塞语义。
 *
 * ---------------------------------------------------------------------------
 * 临界区
 * ---------------------------------------------------------------------------
 * 与队列一致：本组件自己关中断（它是顶层组件，给应用直接调用），
 * 内部调用的 scheduler_wake_one() 不再关中断 —— 全工程只有一层临界区。
 *=========================================================================*/

typedef struct {
    volatile uint16_t count;   /* 当前计数值                      */
    uint16_t          max;     /* 上限；give 时达到上限则饱和丢弃 */
} sched_sem_t;

/*---------------------------------------------------------------------------
 * 创建信号量
 *
 *   init : 初始计数值
 *   max  : 计数值上限（>= 1）。传 1 即为二值信号量
 *
 * 返回：句柄；失败返回 NULL（参数非法 / 内存池不足）
 *
 * 注意：必须在 scheduler_init() 之后调用 —— 控制块从 port_mem 分配。
 *--------------------------------------------------------------------------*/
sched_sem_t *scheduler_sem_create(uint16_t init, uint16_t max);

/*---------------------------------------------------------------------------
 * 获取（P 操作）
 *
 *   timeout_ms = 0 → 永久等待；> 0 → 限时等待
 *
 * 返回：1 拿到令牌；0 超时（或参数非法 / 调度器未启动）
 *
 * 只能在任务上下文调用。
 *--------------------------------------------------------------------------*/
int scheduler_sem_take(sched_sem_t *sem, uint32_t timeout_ms);

/*---------------------------------------------------------------------------
 * 释放（V 操作）
 *
 * 可在 ISR 中调用。若有任务正阻塞等待，令牌直接过继给它（count 不变）；
 * 否则 count++，达到 max 则本次 give 被丢弃（饱和）。
 *--------------------------------------------------------------------------*/
void scheduler_sem_give(sched_sem_t *sem);

/* 当前计数值（调试用） */
uint16_t scheduler_sem_count(sched_sem_t *sem);

#endif /* __SCHEDULER_SEM_H */
