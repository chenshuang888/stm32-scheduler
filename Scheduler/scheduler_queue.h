#ifndef __SCHEDULER_QUEUE_H
#define __SCHEDULER_QUEUE_H

#include "main.h"

/*===========================================================================
 * scheduler_queue — 定长消息队列
 *
 * 定位：调度器配套的 IPC 原语。但 scheduler.c 不依赖本模块 —— 队列是
 *       "内核提供、应用可选"的组件，删掉本文件内核照常工作。
 *
 * ---------------------------------------------------------------------------
 * 为什么是"定长"消息
 * ---------------------------------------------------------------------------
 * 变长队列需要 [长度前缀][数据...] 的紧凑布局，send 时还要判断环形区里
 * 剩余空间是否连续、不连续就得拆分存储，边界情况多、极易出隐性 bug。
 * 定长则退化成最简单的 head/tail/count 三变量环形缓冲，逻辑一眼可验证。
 *
 * 代价是每条消息都占用 item_size 字节（不足则尾部有浪费），但本模块面向
 * 的是"短日志/短命令"这类场景，浪费的几十字节远小于换来的是确定性。
 * 超长消息会被 vsnprintf 截断，对日志而言完全可接受。
 *
 * ---------------------------------------------------------------------------
 * 存储区从哪来（这是本模块最需要解释的设计点）
 * ---------------------------------------------------------------------------
 * 队列的存储区在 create 时从 port_mem **一次性**分配，之后所有 send/recv
 * 都在这块内存里循环复用，永不释放。
 *
 * 这正好匹配 port_mem 的能力边界：它是 bump allocator，只分配不释放。
 * 听起来是缺陷，但对"创建一次、循环使用"的队列而言恰恰是最合适的 ——
 * 零碎片、零块头开销、O(1) 且耗时确定。
 *
 *   !! 千万不要在 send() 里调 scheduler_port_mem_alloc() !!
 *      那样每次发送都会永久吃掉一块内存，几十次打印后池子必然耗尽。
 *
 * 由此也得出使用约束：create 必须在 scheduler_init() 之后调用
 * （port_mem 尚未初始化时分配一律失败）。
 *
 * ---------------------------------------------------------------------------
 * 两种消费方式共存
 * ---------------------------------------------------------------------------
 *   scheduler_queue_recv       非阻塞，取不到立即返回 0，调用方自行轮询
 *   scheduler_queue_recv_block 阻塞挂起，由 send 侧唤醒，可设超时
 *
 * 阻塞能力的实现依赖内核的两个原语：
 *   scheduler_wait_prepare(obj, timeout)  把当前任务挂到 obj 上等待
 *   scheduler_wake_one(obj)               唤醒等待 obj 的最高优先级任务
 * 二者都不自己关中断，由本模块在临界区内调用 —— 全工程只存在一层临界区。
 *
 * 中断上下文的使用限制：
 *   send / recv / peek 都不阻塞，ISR 中可以直接调用 send
 *   （唤醒动作只是链表操作，中断里执行是安全的）。
 *   recv_block 只能在任务上下文调用 —— 它会挂起当前任务。
 *   调度器尚未启动时调用 recv_block 会退化为非阻塞，直接返回 0。
 *=========================================================================*/

typedef struct {
    uint8_t          *buf;        /* 存储区首地址（port_mem 一次性分配） */
    volatile uint16_t head;       /* 队头：下一次 recv 取走的位置        */
    volatile uint16_t tail;       /* 队尾：下一次 send 放入的位置        */
    volatile uint16_t count;      /* 当前消息条数                        */
    uint16_t          item_size;  /* 每条消息字节数（已向上对齐到 4）    */
    uint16_t          capacity;   /* 队列容量（条数）                    */
} sched_queue_t;

/*---------------------------------------------------------------------------
 * 对外接口
 *--------------------------------------------------------------------------*/

/*---------------------------------------------------------------------------
 * 创建队列
 *
 *   item_size : 每条消息的字节数，内部会向上对齐到 4
 *   capacity  : 队列容量（最多容纳多少条消息）
 *
 * 返回：成功返回队列句柄；失败返回 NULL
 *       （参数非法 / 乘法溢出 / 内存池空间不足）
 *
 * 注意：必须在 scheduler_init() 之后调用 —— 存储区来自 port_mem。
 *
 * 内存开销 = item_size(对齐后) × capacity  +  sizeof(sched_queue_t)
 * 例：64 × 8 = 512 B + 16 B。可用 scheduler_port_mem_used() 复核。
 *--------------------------------------------------------------------------*/
sched_queue_t *scheduler_queue_create(uint16_t item_size, uint16_t capacity);

/*---------------------------------------------------------------------------
 * 入队：把 item 指向的 item_size 字节**拷贝**进队列
 *
 * 返回：1 成功；0 失败（队列满 / 参数非法）
 *
 * 队列满时的策略是**丢弃新消息**，不覆盖最老的一条：
 *   日志场景里"保留历史、丢掉最新"比"丢掉最早"更容易定位问题，
 *   也与"不阻塞调用方"的原则一致 —— 调试输出不该把业务任务卡住。
 *
 * !! 只拷贝不持有指针 !!
 *    调用方通常传栈上局部数组（如 char tmp[64]）。若队列只存指针，
 *    函数返回 / 任务被抢占后指针即失效，取出的将是垃圾数据。
 *--------------------------------------------------------------------------*/
int scheduler_queue_send(sched_queue_t *q, const void *item);

/*---------------------------------------------------------------------------
 * 出队：把队头消息**拷贝**到 item 指向的 item_size 字节缓冲区
 *
 * 返回：1 成功；0 失败（队列空 / 参数非法）
 *
 * 非阻塞：空队列立即返回 0，调用方需自行延时重试。典型消费循环：
 *
 *     while (1)
 *     {
 *         while (scheduler_queue_recv(q, msg))
 *             handle(msg);
 *         scheduler_delay(5);      // 让出 CPU，不是忙等
 *     }
 *--------------------------------------------------------------------------*/
int scheduler_queue_recv(sched_queue_t *q, void *item);

/*---------------------------------------------------------------------------
 * 阻塞版出队：队列空时挂起当前任务，直到有消息入队或超时
 *
 *   timeout_ms = 0 → 永久等待
 *   timeout_ms > 0 → 限时等待
 *
 * 返回：1 取到消息；0 超时（或参数非法 / 调度器未启动）
 *
 * 只能在任务上下文调用。调度器尚未启动时（current_tcb == NULL）
 * 无法挂起，会自动退化成"看一眼就返回"的非阻塞语义。
 *
 * 无消息时任务完全不参与调度，CPU 交给 Idle —— 相比 recv + delay 轮询，
 * 既消除了轮询唤醒开销，也把响应延迟从"最多一个轮询周期"降到微秒级。
 *--------------------------------------------------------------------------*/
int scheduler_queue_recv_block(sched_queue_t *q, void *item, uint32_t timeout_ms);

/* 取队头消息但不移除。返回 1 成功 / 0 队列空。用于"先探一眼再决定"的场景 */
int scheduler_queue_peek(sched_queue_t *q, void *item);

/* 当前消息条数 / 剩余空位 */
uint16_t scheduler_queue_count(const sched_queue_t *q);
uint16_t scheduler_queue_space(const sched_queue_t *q);

/* 清空队列（丢弃全部消息）。仅复位索引，不擦除存储区内容 */
void scheduler_queue_reset(sched_queue_t *q);

#endif /* __SCHEDULER_QUEUE_H */
