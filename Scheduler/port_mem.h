#ifndef __PORT_MEM_H
#define __PORT_MEM_H

#include "main.h"       /* uint32_t / uint8_t / NULL，并间接引入 stdint.h */

/*===========================================================================
 * port_mem — 调度器内存分配移植层
 *
 * 职责：为调度器提供 TCB 与任务栈的内存来源。
 * 与 port_asm.s（上下文切换）、port_timer.c（时基）共同构成移植层。
 *
 * 当前实现：单向线性分配器（bump allocator）
 *
 *   维护一个游标 mem_used_words，每次分配就向前推进，不支持释放。
 *   这听起来是缺陷，但对"任务只创建一次、运行期不删除"的场景而言
 *   恰恰是最合适的选择：
 *
 *     1. 零碎片 —— 碎片由"释放"产生，不释放就不会有碎片。
 *        FreeRTOS 专门保留 heap_1（只分配不释放）就是给这类场景用的。
 *     2. 零元数据开销 —— 通用 malloc 每块要带 8~16 字节块头，本实现为 0。
 *     3. O(1) 且耗时确定 —— 不遍历空闲链表，不受堆历史状态影响。
 *     4. RAM 占用编译期可见 —— 整池落在 .bss，链接器可直接看出总量。
 *
 * 若将来需要支持删除任务，只需把本文件内部替换为带空闲链表与相邻块
 * 合并的实现（heap_4 风格），对外接口保持不变，上层无需改动。
 *
 * !! 最重要的约束：返回的指针恒为 8 字节对齐 !!
 *    ARM AAPCS 要求函数调用时 SP 8 字节对齐。任务栈若非 8 对齐，
 *    printf 的 %f（double 参数）写入与读取位置会系统性错开，
 *    打印出天文数字；带 %s 时更会把错位数据当地址解引用而 HardFault。
 *    本模块通过"池起始 8 对齐 + 每次分配偶数个字"来保证这一不变式。
 *=========================================================================*/

/* 内存池容量（单位：字，1 字 = 4 字节）
 *
 * 当前需求（4 个任务）：
 *   栈  LED 512B + UART 1KB + ICM 2KB + IDLE 256B = 3840 B
 *   TCB 4 × 32 B                                  =  128 B
 *                                                  ────────
 *                                                   ≈ 4 KB
 *
 * 2048 字 = 8 KB，留约一倍余量给后续动态创建的任务。
 * 跑起来后用 scheduler_port_mem_used() 读出真实用量，再把本值
 * 精调为"实际用量 + 30% 余量"即可。
 */
#define MEM_POOL_WORDS   2048

/*---------------------------------------------------------------------------
 * 对外接口
 *--------------------------------------------------------------------------*/

/* 初始化内存池。必须在任何分配之前调用一次（scheduler_init() 的第一行）。
   会把游标归零，但不清空池内容 —— 分配出去的内存由调用者立即初始化。 */
void scheduler_port_mem_init(void);

/* 从池中分配 bytes 字节。
 *
 * 返回：8 字节对齐的内存起始地址；失败返回 NULL（池空间不足或尚未初始化）。
 *
 * 注意：
 *   1. 返回的内存内容未清零，调用者需自行初始化
 *   2. 本分配器不支持释放，分配出去的空间不会回收
 */
void *scheduler_port_mem_alloc(uint32_t bytes);

/* 已分配字节数。用于实测真实需求，进而精调 MEM_POOL_WORDS */
uint32_t scheduler_port_mem_used(void);

/* 剩余可用字节数 */
uint32_t scheduler_port_mem_free(void);

#endif /* __PORT_MEM_H */
